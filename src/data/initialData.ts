export const getDistrictsForRegion = (regionName?: string): string[] => {
  if (!regionName) return [...HSU_DISTRICTS];
  if (KALSEL_DISTRICTS_MAP[regionName]) {
    return KALSEL_DISTRICTS_MAP[regionName];
  }
  const matched = Object.keys(KALSEL_DISTRICTS_MAP).find(
    (k) => regionName.toLowerCase().includes(k.toLowerCase()) || k.toLowerCase().includes(regionName.toLowerCase())
  );
  return matched ? KALSEL_DISTRICTS_MAP[matched] : [...HSU_DISTRICTS];
};

